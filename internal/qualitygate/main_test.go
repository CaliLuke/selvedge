package main

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func testSource(t *testing.T, root, name, source string) {
	t.Helper()
	require.NoError(t, os.WriteFile(filepath.Join(root, name), []byte(source), 0600))
}

func TestInventoryIncludesOwnedExecutableSources(t *testing.T) {
	root := t.TempDir()
	testSource(t, root, "a.go", `package example
import "io"
type Store[T any] struct { In io.Reader; Out io.Writer }
func (s *Store[T]) Read() { println("read") }
func (s Store[T]) Write() {}
`)
	testSource(t, root, "generated.go", "// Code generated by example. DO NOT EDIT.\npackage example\nfunc Generated() {}\n")
	data, err := json.Marshal(packageInfo{Dir: root, ImportPath: "example", GoFiles: []string{"a.go", "generated.go"}})
	require.NoError(t, err)
	r, err := inventory(root, bytes.NewReader(data))
	require.NoError(t, err)
	require.Equal(t, []string{"a.go"}, r.Packages["example"])
	require.Equal(t, []string{"generated.go"}, r.GeneratedFiles)
	require.Equal(t, []string{"a.go"}, r.CoverageFiles)
	require.Len(t, r.SourceHashes["a.go"], 64)
}

func TestInventoryRejectsIncompleteAnalysis(t *testing.T) {
	for _, input := range []string{"", "{", `{}`, `{"ImportPath":"x","Error":{"Err":"cannot load"}}}`, `{"ImportPath":"x"}{"ImportPath":"x"}`} {
		_, err := inventory(t.TempDir(), strings.NewReader(input))
		require.Error(t, err)
	}
}

func TestInventoryRejectsMissingAndExternalSources(t *testing.T) {
	root := t.TempDir()
	for _, name := range []string{"missing.go", "../external.go"} {
		data, err := json.Marshal(packageInfo{Dir: root, ImportPath: "x", GoFiles: []string{name}})
		require.NoError(t, err)
		_, err = inventory(root, bytes.NewReader(data))
		require.Error(t, err)
	}
	testSource(t, root, "bad.go", "package")
	data, err := json.Marshal(packageInfo{Dir: root, ImportPath: "x", GoFiles: []string{"bad.go"}})
	require.NoError(t, err)
	_, err = inventory(root, bytes.NewReader(data))
	require.Error(t, err)
}

func TestRunLoadsActualPackageInventory(t *testing.T) {
	root := t.TempDir()
	t.Chdir(root)
	testSource(t, root, "go.mod", "module example.com/fixture\n\ngo 1.27.3\n")
	testSource(t, root, "a.go", "package fixture\nfunc Run() { println(1) }\n")
	var output bytes.Buffer
	require.NoError(t, run(&output))
	var r report
	require.NoError(t, json.Unmarshal(output.Bytes(), &r))
	require.Equal(t, []string{"a.go"}, r.Packages["example.com/fixture"])
	testSource(t, root, "go.mod", "invalid module file")
	require.Error(t, run(&output))
}
